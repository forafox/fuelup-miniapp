package ru.fuelup.common.order;

public enum OrderStatus {
    /** Заказ создан в нашей системе, ожидает подтверждения от партнёра */
    PENDING,
    /** Партнёр принял заказ, сформирована ссылка на оплату */
    PLACED,
    /** Платёж успешно проведён, топливо выдаётся */
    PAID,
    /** Заправка завершена, зафиксирован фактический объём */
    COMPLETED,
    /** Заказ отменён пользователем или партнёром */
    CANCELLED,
    /** Ошибка при создании или обработке заказа */
    FAILED,
}
